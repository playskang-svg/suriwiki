/**
 * lib/region-short-name.ts
 * ------------------------------------------------------------------------
 * 썸네일(OG 이미지) 전용 지역명 축약. 정식 명칭 끝의 행정단위를 떼어낸다 —
 * "서울특별시"→"서울", "관악구"→"관악", "불당동"→"불당"처럼. 사람이 봐도 어차피
 * 알아볼 수 있는 지역명이라, 썸네일 안에서는 이 정도로 짧아도 된다는 요청 반영
 * ("썸네일이만 짧게... 서울시를 그냥 서울... 구나 동 리도 빼도 상관 없겠네").
 *
 * 브레드크럼·H1·<title>·JSON-LD 등 텍스트는 검색엔진 노출을 위해 정식 명칭을
 * 그대로 쓴다 — 이 축약은 오직 썸네일 이미지 렌더링에서만 쓴다.
 *
 * 긴 복합 접미사(특별자치시 등)부터 먼저 검사해야 "전남광주통합특별시"에서
 * "특별시"만 떼고 "통합"이 남는 실수를 막을 수 있다 — 그래서 배열 순서가 중요하다.
 * ------------------------------------------------------------------------
 */
const TRAILING_UNIT_RE =
  /(특별자치시|특별자치도|통합특별시|광역시|특별시|자치시|자치도|시|도|군|구|읍|면|동|리)$/

/** 지역명 끝의 행정단위(시/도/군/구/읍/면/동/리 등)를 떼어낸 축약형. 못 떼면 원본 그대로. */
export function shortenRegionNameForThumbnail(name: string): string {
  const stripped = name.replace(TRAILING_UNIT_RE, '')
  return stripped || name
}
